    /** @return array<string, array{0: string, 1: string, 2?: bool}> */
    public static function textDefinitions(): array
    {
        return array_merge(...array_values(self::TEXTS));
    }

    /** @return array<string, string> كل نصوص الواجهة بقيمها الحالية */
    public static function texts(): array
    {
        return collect(self::textDefinitions())
            ->map(fn ($def, $key) => (string) (Setting::get('ui_'.$key) ?: $def[1]))->all();
    }

    public static function on(string $feature): bool
    {
        return Setting::get('on_'.$feature, '1') !== '0';
    }

    /** @return string[] مفاتيح أقسام الرئيسية الظاهرة بالترتيب المختار */
    public static function sections(): array
    {
        $saved = json_decode((string) Setting::get('home_sections'), true);
        $order = is_array($saved) ? $saved : array_map(fn ($k) => ['key' => $k, 'on' => true], array_keys(self::SECTIONS));
        $known = array_column($order, 'key');
        foreach (array_keys(self::SECTIONS) as $key) {
            if (! in_array($key, $known, true)) {
                $order[] = ['key' => $key, 'on' => true]; // قسم أضيف في تحديث لاحق
            }
        }

        return array_values(array_filter($order, fn ($s) => isset(self::SECTIONS[$s['key'] ?? '']))) ;
    }

    /** @return string[] */
    public static function visibleSections(): array
    {
        return array_column(array_filter(self::sections(), fn ($s) => $s['on'] ?? true), 'key');
    }

    /** @return array<string, string> الألوان التي غيّرها المدير فقط */
    public static function customColors(): array
    {
        $out = [];
        foreach (self::COLORS as $key => [, $default]) {
            $value = strtolower((string) Setting::get('color_'.$key));
            if (preg_match('/^#[0-9a-f]{6}$/', $value) && $value !== $default) {
                $out[$key] = $value;
            }
        }

        return $out;
    }
